def load_config(path):
    cfg = {}
    if not os.path.exists(path):
        return cfg
    try:
        with open(path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                if '=' not in line:
                    continue
                k, v = line.split('=', 1)
                k = k.strip().replace('-', '_')
                v = v.strip().strip('"').strip("'")
                cfg[k] = v
    except Exception:
        pass
    return cfg


def _as_bool(v, default):
    if v is None:
        return default
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() in ('1', 'true', 'yes', 'on')


def _as_float(v, default):
    if v is None:
        return default
    try:
        return float(v)
    except ValueError:
        return default


def write_config(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = [f'# word-sync configuration (v{VERSION})', '']
    order = ('font', 'scale', 'fill', 'gap', 'color', 'color_mode', 'bg',
             'outline', 'bold', 'glow', 'shadow', 'glow_color', 'case',
             'v_offset', 'transition', 'fade', 'paused_dim',
             'player', 'plain', 'resync', 'tick', 'lyrics_dir', 'cache_dir')
    for k in order:
        if k in data and data[k] is not None:
            v = data[k]
            if isinstance(v, bool):
                lines.append(f'{k} = {str(v).lower()}')
            elif isinstance(v, (int, float)):
                lines.append(f'{k} = {v}')
            else:
                lines.append(f'{k} = "{v}"')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


