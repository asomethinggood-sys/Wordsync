# Offline regression suite (--selftest)
# --------------------------------------------------------------------------
def run_selftest():
    """Offline rendering, parser, prosody, cadence and stereo-audio regression checks."""
    fails = []

    def check(cond, label):
        if not cond:
            fails.append(label)

    samples = {
        'latin': 'NEON WORDS 123',
        'cyrillic': 'ПРИВЕТ СЛОВА ЖИЗНЬ',
        'accents': 'DÎNER ÊTÉ ÇA M’ATTENDRE…',
        'hiragana': 'きらそめたむすびね',
        'katakana': 'カタカナノテスト ヴぱ',
    }
    for fname, font in FONTS.items():
        for label, w in samples.items():
            rows = generate_glyph_rows(w, font, '█', ' ', 1, False, 'asis', False)
            ink = sum(1 for r in rows for c in r if c != ' ')
            check(ink > 0, f'{fname}/{label} rendered blank')
            check(len({len(r) for r in rows}) == 1, f'{fname}/{label} ragged rows')

    lrc = ('[offset:-200]\n[00:10.00]he' + chr(0x301) + 'llo wo' + chr(0x308) + 'rld\n'
           '[00:12.00]<00:12.00>un <00:12.5>deux\n')
    lines = parse_lrc(lrc)
    check(len(lines) == 2 and abs(lines[0]['start'] - 10.2) < 1e-6, 'lrc offset tag')
    check(lines[0]['text'] == 'h' + chr(0xE9) + 'llo w' + chr(0xF6) + 'rld',
          'lrc NFC normalisation')
    check(bool(lines[1]['words']) and len(lines[1]['words']) == 2, 'lrc word tags')

    check(syllables("c'était") == 2, 'syllable elision')
    check(syllables('любовь') >= 2, 'syllable cyrillic')
    check(syllables('사랑해') == 3, 'syllable hangul')

    pop = [
        {'start': 0.0, 'text': 'comme cet homme est venu me voir', 'words': None},
        {'start': 4.0, 'text': 'pour parler de mon amoureux', 'words': None},
        {'start': 8.0, 'text': 'je savais que c’était lui que', 'words': None},
        {'start': 28.0, 'text': 'attendais depuis toujours', 'words': None},
    ]
    evs = build_word_events(pop, 60.0)
    ts = [t for t, _ in evs]
    check(ts == sorted(ts), 'events monotonic')
    last_onset = max((t for t, w in evs if w and t < 20), default=0.0)
    clears = [t for t, w in evs if not w and 8.0 < t < 28.0]
    check(bool(clears) and clears[0] < 20.0, 'verse-end rest cleared')
    check(last_onset - 8.0 < 8.0, f'verse-end span too long ({last_onset - 8.0:.1f}s)')

    def first_line_span(win):
        ls = [{'start': i * win, 'text': 'je t’aime encore ce soir', 'words': None}
              for i in range(6)]
        e = build_word_events(ls, win * 8)
        on = [t for t, w in e if w and t < win]
        return (on[-1] - on[0]) if on else 0.0
    check(first_line_span(7.0) > first_line_span(3.0), 'tempo-adaptive cadence')
    check(first_line_span(7.0) < 6.2, 'ballad words stay with the vocal (no late drift)')

    # Panchiko/post-phrase gap archetype: sparse 6.5 s windows mixed with dense vocal lines.
    panchiko_windows = [6.5, 2.2, 6.2, 2.4, 6.5, 2.1, 6.0, 2.3, 6.4, 2.2]
    panchiko_lines, cursor = [], 0.0
    for window in panchiko_windows:
        panchiko_lines.append({'start': cursor, 'text': 'we can see light tonight',
                               'words': None})
        cursor += window
    panchiko_meta = {}
    panchiko_events = build_word_events(panchiko_lines, cursor + 2.0, meta=panchiko_meta)
    first_spec = panchiko_meta['line_specs'][0]
    panchiko_onsets = [t for t, word in first_spec['events'] if word]
    panchiko_clear = [t for t, word in first_spec['events'] if not word]
    check(syllables('tonight') + 4 == 6, 'Panchiko fixture has six syllables')
    check(bool(panchiko_onsets) and panchiko_onsets[-1] - first_spec['start'] <= 2.4,
          'Panchiko 6-syllable words finish within 2.4 s')
    check(bool(panchiko_clear) and panchiko_clear[0] - first_spec['start'] < 3.5,
          'Panchiko post-phrase gap emits early rest marker')

    prosodic_words = line_words('Wait, in the middle of the night')
    prosodic_events = estimate_line(prosodic_words, 0.0, 4.8, 0.45)
    plain_events = estimate_line(line_words('Wait in the middle of the night'), 0.0, 4.8, 0.45)
    prosodic_times = [t for t, word in prosodic_events if word]
    plain_times = [t for t, word in plain_events if word]
    articulation, _ = _prosodic_durations(prosodic_words, 0.45, 4.8)
    check(prosodic_times[1] - prosodic_times[0] >
          plain_times[1] - plain_times[0] + 0.14, 'comma lengthening and caesura pause')
    check(max(articulation[i] for i in (1, 2, 4, 5)) <
          min(articulation[3], articulation[6]), 'function words compressed vs content words')

    tempo_lines, cursor = [], 0.0
    for i in range(16):
        is_rap = i < 8
        tempo_lines.append({'start': cursor,
                            'text': ' '.join(['beat'] * (12 if is_rap else 5)),
                            'words': None})
        cursor += 2.5 if is_rap else 4.5
    tempo_meta = {}
    build_word_events(tempo_lines, cursor + 2.0, meta=tempo_meta)
    tempo_paces = tempo_meta['line_paces']
    check(tempo_paces[9] > tempo_paces[7] * 1.5,
          'local cadence adapts within two lines of a beat switch')

    # Wide side-channel instrumental energy cancels; center-panned vocal should be the VAD.
    sample_rate, audio_bytes = 16000, bytearray()
    for sample in range(sample_rate * 6):
        t = sample / float(sample_rate)
        side = 0.18 * (math.sin(2 * math.pi * 440 * t) +
                       0.45 * math.sin(2 * math.pi * 900 * t) +
                       0.25 * math.sin(2 * math.pi * 2800 * t))
        if 0.4 <= t < 2.0:
            phase = t - 0.4
            envelope = 0.55 + 0.45 * max(0.0, math.sin(2 * math.pi * 3.0 * phase))
            vocal = 0.35 * envelope * math.sin(
                2 * math.pi * (620 + 40 * math.sin(2 * math.pi * 4 * phase)) * t)
        else:
            vocal = 0.0
        left, right = side + vocal, -side + vocal
        audio_bytes.extend(struct.pack('<hh', int(max(-1, min(1, left)) * 32767),
                                       int(max(-1, min(1, right)) * 32767)))
    tracker = LiveAudioTracker(enabled=False)
    stereo_features = tracker.feed_pcm(bytes(audio_bytes), 0.0)
    active_positions = [f.song_position for f in stereo_features if f.vad]
    check(bool(active_positions) and min(active_positions) >= 0.35 and
          max(active_positions) <= 2.05, 'stereo mid-side VAD isolates center vocal burst')
    check(not any(f.vad for f in stereo_features
                  if f.song_position < 0.35 or f.song_position > 2.15),
          'stereo-panned instrumental is rejected outside vocal')
    aligned = align_tokens(['wait', 'for', 'the', 'light'], stereo_features, 0.0, 6.0, 0.45)
    aligned_onsets = [t for t, word in aligned if word]
    check(bool(aligned_onsets) and 0.35 <= aligned_onsets[0] <= 0.50 and
          aligned_onsets[-1] <= 2.05, 'audio alignment snaps word onsets inside vocal burst')
    tracker.stop()

    if fails:
        sys.stderr.write('selftest FAILED:\n  ' + '\n  '.join(fails) + '\n')
        return 1
    sys.stdout.write(f'selftest OK — {len(FONTS)} fonts x {len(samples)} scripts, '
                     'parser, prosodic cadence, rest handling and stereo audio all pass\n')
    return 0


