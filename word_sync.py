_PUNCTUATION_ENDINGS = (('...', 0.30), ('…', 0.30), (';', 0.27), (':', 0.25),
                        ('—', 0.28), ('–', 0.26), ('-', 0.24), ('?', 0.28),
                        ('!', 0.27), (',', 0.18), ('.', 0.20))
_CLOSING_PUNCT = '"\'”’»)]}'


def _spoken_token(token):
    """Return a case-folded lexical form while retaining internal hyphens/apostrophes."""
    return unicodedata.normalize('NFKC', str(token)).strip().lower().strip(
        '.,;:!?…—–-()[]{}"\'“”‘’«»')


def _punctuation_kind(token):
    raw = str(token).rstrip(_CLOSING_PUNCT).rstrip()
    for mark, pause in _PUNCTUATION_ENDINGS:
        if raw.endswith(mark):
            return mark, pause
    return '', 0.0


def _is_clause_boundary(token):
    return bool(_punctuation_kind(token)[0])


def _parenthetical_starts(token):
    return str(token).lstrip().startswith(('(', '['))


def _is_function_word(token):
    return _spoken_token(token).replace('’', "'") in UNSTRESSED_FUNCTION_WORDS


def _heavy_word(token):
    clean = _spoken_token(token)
    return syllables(clean) >= 2 or (len(clean) >= 4 and
            sum(1 for c in clean if c in 'aeiouyàâäéèêëîïôöùûü') / max(1, len(clean)) >= 0.48)


def _stutter_count(token):
    parts = _spoken_token(token).split('-')
    if len(parts) >= 3 and all(len(p) <= 2 for p in parts[:-1]):
        return len(parts) - 1
    return 1


def _repeat_transition(words, left, right):
    """True for identical words or short, one-syllable alliterative chant sequences."""
    a, b = _spoken_token(words[left]), _spoken_token(words[right])
    if not a or not b:
        return False
    if a == b:
        return True
    return (len(a) <= 4 and len(b) <= 4 and syllables(a) == syllables(b) == 1
            and a[0].isalpha() and a[0] == b[0])


def _prosodic_durations(words, pace, raw_window):
    """Per-word articulation and punctuation gaps, retaining raw token punctuation."""
    n = len(words)
    if not n:
        return [], []
    clean = [_spoken_token(w) for w in words]
    syl = [syllables(w) for w in clean]
    articulation = []
    requested_pauses = []
    pickup_active = (n >= 2 and _is_function_word(words[0]) and
                     (_is_function_word(words[1]) or _heavy_word(words[1])))
    pickup_count = 0
    for i, word in enumerate(words):
        func = _is_function_word(word)
        boundary, _ = _punctuation_kind(word)
        parenthetical_next = i + 1 < n and _parenthetical_starts(words[i + 1])
        pre_boundary = bool(boundary or parenthetical_next)
        # Function words at clause ends are not reduced; ordinary function words are quick
        # pickups, with an extra anacrusis compression on the first one or two words.
        multiplier = 0.56 if func and i < n - 1 and not pre_boundary else 1.0
        if pickup_active and func and pickup_count < 2:
            multiplier *= 0.82
            pickup_count += 1
        if pre_boundary:
            multiplier *= 1.25
        display_lexeme = str(word).strip('.,;:!?…—–-()[]{}"\'“”‘’«»')
        if not func and display_lexeme.isupper() and len(clean[i]) > 1:
            multiplier *= 1.04  # explicit all-caps emphasis, conservatively weighted
        stutter_units = _stutter_count(word)
        if stutter_units > 1:
            multiplier *= min(1.28, 1.0 + 0.12 * (stutter_units - 1))
        # Keep polysyllabic words prominent without giving them the old flat character-only
        # treatment. This concave curve also leaves room for stress and function-word cues.
        syllable_weight = max(0.55, syl[i] ** TUNE['syl_exp'])
        articulation.append(max(0.045, pace * syllable_weight * multiplier))

        _, punctuation_pause = _punctuation_kind(word)
        if i + 1 < n and _parenthetical_starts(words[i + 1]):
            punctuation_pause = max(punctuation_pause, 0.28)
        requested_pauses.append(punctuation_pause if i + 1 < n else 0.0)

    # Caesurae use only genuine slack; many commas cannot consume more time than is present.
    pause_budget = max(0.0, raw_window - sum(articulation) -
                       min(TUNE['hold_cap'], TUNE['hold_a'] + TUNE['hold_b'] * pace))
    requested_total = sum(requested_pauses)
    pause_scale = min(1.0, pause_budget / requested_total) if requested_total else 0.0
    pauses = [p * pause_scale for p in requested_pauses]
    return articulation, pauses


def _isochronous_onset_gaps(words, articulation, pauses, pace):
    gaps = [articulation[i] + pauses[i] for i in range(max(0, len(words) - 1))]
    i = 0
    while i < len(words) - 1:
        if not _repeat_transition(words, i, i + 1):
            i += 1
            continue
        end = i + 1
        while end < len(words) - 1 and _repeat_transition(words, end, end + 1):
            end += 1
        group = words[i:end + 1]
        beat = min(0.58, max(0.16, pace * sum(syllables(_spoken_token(w)) for w in group) /
                                           max(1, len(group)) * 0.96))
        for k in range(i, end):
            gaps[k] = beat
        i = end + 1
    return gaps


def estimate_line(words, line_start, line_end, pace=DEFAULT_PACE):
    """Estimate word onsets from prosodic articulation, punctuation and local cadence.

    Onset spacing ends at the *onset* of the final word. The final word's articulation and
    held vowel are accounted for only when calculating clear_at; they never push earlier
    word onsets later. Large post-phrase gaps (> 0.8 s after the phrase's natural duration)
    therefore remain rests rather than being mistaken for sung syllables.
    """
    words = list(words)
    n = len(words)
    if not n:
        return []
    raw_window = line_end - line_start
    if raw_window <= 0.0:
        return [(line_start + i * 1e-6, w) for i, w in enumerate(words)]
    if raw_window < n * 0.004:
        step = raw_window * 0.9 / max(1, n - 1) if n > 1 else 0.0
        return [(line_start + i * step, w) for i, w in enumerate(words)]

    pace = min(TUNE['pace_max'], max(TUNE['pace_min'], float(pace)))
    syl = [syllables(_spoken_token(w)) for w in words]
    articulation, pauses = _prosodic_durations(words, pace, raw_window)
    onset_gaps = _isochronous_onset_gaps(words, articulation, pauses, pace)
    final_hold = min(TUNE['hold_cap'], TUNE['hold_a'] + TUNE['hold_b'] * pace)
    phrase_total_span = sum(articulation) + sum(pauses) + final_hold
    # Onsets are the strict cumulative prosodic durations of all words except the final word,
    # plus internal caesurae. Neither final sustain nor unused slack can stretch them. Whenever
    # raw_window > phrase_total_span + 0.8 s, that excess remains a post-phrase tail (including
    # modest 3.5–5 s windows); the words stay anchored at line_start for the whole window.
    limit = max(0.0, raw_window - TAIL_GUARD)
    last_word_min_dur = max(MIN_SHOW, articulation[-1])
    onset_span = min(sum(onset_gaps), max(0.0, limit - last_word_min_dur))
    if n > 1 and onset_span <= 1e-12:
        micro_step = min(0.001, raw_window * 0.9 / (n - 1))
        return [(line_start + i * micro_step, word) for i, word in enumerate(words)]
    gap_total = sum(onset_gaps)
    ratio = onset_span / gap_total if gap_total > 1e-12 else 0.0
    effective_gaps = [g * ratio for g in onset_gaps]
    if effective_gaps and onset_span > 0.0:
        floor = min(0.001, onset_span / len(effective_gaps))
        effective_gaps = [max(floor, g) for g in effective_gaps]
        total_effective = sum(effective_gaps)
        if total_effective > onset_span:
            scale = onset_span / total_effective
            effective_gaps = [g * scale for g in effective_gaps]

    times = [line_start]
    for gap in effective_gaps:
        times.append(times[-1] + gap)
    out = list(zip(times, words))

    # The final articulation and sustain happen after the final onset, not inside onset_span.
    clear_at = times[-1] + articulation[-1] + final_hold
    if line_end - clear_at >= REST_CLEAR_MIN:
        out.append((clear_at, ''))
    return out


def normalise_line_starts(lines):
    """Repair impossible timing before estimation: lines closer than MIN_LINE_GAP are pushed
    forward (real per-word timings shift with their line). Inputs are not mutated."""
    out = []
    for src_line in sorted(lines, key=lambda x: x['start']):
        l = dict(src_line)
        if out and l['start'] < out[-1]['start'] + MIN_LINE_GAP:
            shift = (out[-1]['start'] + MIN_LINE_GAP) - l['start']
            l['start'] += shift
            if l.get('words'):
                l['words'] = [(t + shift, w) for t, w in l['words']]
        out.append(l)
    return out


def _nearest_rank_percentile(values, percentile):
    ordered = sorted(values)
    if not ordered:
        return DEFAULT_PACE
    rank = max(0, min(len(ordered) - 1, int(math.ceil(percentile * len(ordered))) - 1))
    return ordered[rank]


def _lower_half_median(values):
    ordered = sorted(values)
    if not ordered:
        return DEFAULT_PACE
    lower = ordered[:max(1, (len(ordered) + 1) // 2)]
    middle = len(lower) // 2
    if len(lower) % 2:
        return lower[middle]
    return (lower[middle - 1] + lower[middle]) / 2.0


def _song_cadences(lines, total_duration=None):
    """Return a dense-frontier base pace and robust five-line local paces.

    Per-line rates are seconds per syllable, corrected by the existing voiced-fraction curve.
    The nearest-rank 27th percentile deliberately anchors to the fast, dense phrase frontier;
    sparse lyric timestamps are treated as possible held vowels/instrumental rests.
    """
    rates = [None] * len(lines)
    syllable_counts = [0] * len(lines)
    for i, line in enumerate(lines):
        if i + 1 < len(lines):
            end = lines[i + 1]['start']
        elif total_duration and total_duration > line['start']:
            end = min(total_duration, line['start'] + 6.0)
        else:
            end = line['start'] + 6.0
        window = end - line['start']
        tokens = line_words(line.get('text', ''))
        count = sum(syllables(_spoken_token(token)) for token in tokens)
        syllable_counts[i] = count
        if 0.6 < window < 12.0 and count:
            rates[i] = (window / count) * _voiced_fraction(window)

    eligible = [i for i, rate in enumerate(rates) if rate is not None]
    multiword = [i for i in eligible if syllable_counts[i] >= 3 and
                 len(line_words(lines[i].get('text', ''))) >= 2]
    frontier_indices = multiword if len(multiword) >= 3 else [
        i for i in eligible if syllable_counts[i] >= 3]
    frontier = [rates[i] for i in frontier_indices]
    if len(frontier) >= 1:
        # With only one sparse anchor, shrink toward a musical prior instead of declaring
        # a single timestamp interval to be a whole-song slow-motion tempo.
        ordered_frontier = sorted(frontier)
        dense = _nearest_rank_percentile(ordered_frontier, 0.27)
        # If there are only a couple of genuinely dense phrases among many sparse LRC lines,
        # a literal 27th percentile can land just above a sharp fast/slow mixture boundary.
        # Detect that clear articulation cluster (never micro-interjections; filtered above)
        # and preserve its lower-half cadence as the frontier anchor.
        split_limit = min(len(ordered_frontier) // 2, len(ordered_frontier) - 1)
        for split in range(2, split_limit + 1):
            if ordered_frontier[split] >= 1.6 * ordered_frontier[split - 1]:
                dense = min(dense, _lower_half_median(ordered_frontier[:split]) * 1.05)
                break
        if len(frontier) < 3:
            dense = min(dense, DEFAULT_PACE)
        base_pace = min(TUNE['pace_max'], max(TUNE['pace_min'], dense))
    else:
        base_pace = DEFAULT_PACE

    paces = []
    for i in range(len(lines)):
        nearby = [rates[j] for j in range(max(0, i - 2), min(len(lines), i + 3))
                  if rates[j] is not None and syllable_counts[j] >= 3]
        if not nearby:
            nearby = [rates[j] for j in range(max(0, i - 2), min(len(lines), i + 3))
                      if rates[j] is not None]
        local = _lower_half_median(nearby) if nearby else base_pace
        local = min(TUNE['pace_max'], max(TUNE['pace_min'], local))

        # A lone long line surrounded by a dense/fast frontier is a rest/sustain outlier,
        # not evidence that the singer changed articulation speed for one phrase.
        neighbors = [rates[j] for j in (i - 1, i + 1)
                     if 0 <= j < len(lines) and rates[j] is not None]
        if rates[i] is not None and neighbors and rates[i] > 1.6 * base_pace:
            neighbor_frontier = _lower_half_median(neighbors)
            if neighbor_frontier <= 1.25 * base_pace:
                local = min(local, base_pace * 1.12)

        paces.append(min(TUNE['pace_max'], max(TUNE['pace_min'],
                         0.35 * base_pace + 0.65 * local)))
    return base_pace, paces


def _stretch_line_events(events, line_start, line_end, stretch):
    if stretch == 1.0:
        return list(events)
    fixed = []
    cap = line_end - 1e-3
    previous = line_start - 1.0
    for t, word in events:
        t = min(cap, line_start + (t - line_start) * stretch)
        if t <= previous:
            t = previous + 1e-4
        fixed.append((t, word))
        previous = t
    return fixed


def _compose_word_events(line_specs, prefix_events=()):
    rows = list(prefix_events)
    for spec in line_specs:
        rows.extend(spec.get('events', ()))
    rows.sort(key=lambda event: event[0])
    cleaned = []
    for event in rows:
        if cleaned and cleaned[-1][1] == '' and event[1] == '':
            continue
        cleaned.append(event)
    return cleaned


def build_word_events(lines, total_duration, stretch=1.0, meta=None, audio=None):
    """Flatten lyrics into a sorted (time, word_or_'') timeline.

    Estimated lines use dense-frontier/local cadence and prosodic onset spacing. When an audio
    feature sequence is supplied, its center-vocal onsets refine those estimates. Real source
    word timing is still trusted. ``meta`` also receives line specs for live causal refinement.
    """
    if not lines:
        if meta is not None:
            meta.update({'estimated_lines': 0, 'real_lines': 0, 'base_pace': DEFAULT_PACE,
                         'line_paces': [], 'line_specs': [], 'prefix_events': []})
        return []
    lines = normalise_line_starts(lines)
    if isinstance(audio, (bytes, bytearray)):
        audio_frames = extract_features(audio, start_position=0.0)
    elif hasattr(audio, 'snapshot'):
        audio_frames = audio.snapshot()
    else:
        audio_frames = list(audio or ())
    if not total_duration or total_duration <= 0:
        total_duration = lines[-1]['start'] + 30.0
    base_pace, line_paces = _song_cadences(lines, total_duration)
    prefix_events = [(0.0, '')] if lines[0]['start'] > 2.0 else []
    line_specs = []
    n_est = n_real = 0

    for i, line in enumerate(lines):
        line_start = line['start']
        line_end = (lines[i + 1]['start'] if i + 1 < len(lines) else
                    max(total_duration, line_start + MIN_LINE_GAP))
        pace = line_paces[i]
        real = line.get('words')
        spec = {'line_index': i, 'start': line_start, 'end': line_end, 'pace': pace,
                'estimated': False, 'words': [], 'base_events': [], 'events': []}
        if real:
            ws = [(t, w) for t, w in real if line_start - 0.5 <= t < line_end]
            if ws:
                n_real += 1
                real_events = list(ws)
                if line_end - ws[-1][0] > 3.5:
                    real_events.append((ws[-1][0] + 1.8, ''))
                spec['base_events'] = list(real_events)
                spec['events'] = list(real_events)
                line_specs.append(spec)
                continue

        words = line_words(line.get('text', ''))
        if words:
            n_est += 1
            spec['estimated'] = True
            spec['words'] = list(words)
            has_audio = bool(audio_frames and any(line_start - 0.10 <= f.song_position <= line_end
                                                  for f in audio_frames))
            if has_audio:
                estimated = align_tokens(words, audio_frames, line_start, line_end, pace)
            else:
                estimated = estimate_line(words, line_start, line_end, pace)
            estimated = _stretch_line_events(estimated, line_start, line_end, stretch)
            spec['base_events'] = list(estimated)
            spec['events'] = list(estimated)
        line_specs.append(spec)

    events = _compose_word_events(line_specs, prefix_events)
    if meta is not None:
        meta.update({'estimated_lines': n_est, 'real_lines': n_real,
                     'base_pace': base_pace, 'line_paces': list(line_paces),
                     'line_specs': line_specs, 'prefix_events': list(prefix_events)})
    return events


