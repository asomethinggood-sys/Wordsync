class PlaybackClock:
    """Extrapolates song position between polls and corrects it on every fresh sample.

    * The player read its position somewhere inside the query, so the sample is stamped at the
      MIDPOINT of the round trip (stamping after the call made lyrics run early by the latency).
    * A jump larger than seek_tol, a play/pause change, or a rate change snaps the clock.
    * Smaller disagreements are slewed in gradually so words never jump backwards."""

    def __init__(self, seek_tol=0.35, slew=0.25):
        self.seek_tol, self.slew = seek_tol, slew
        self.anchor_pos = self.anchor_time = 0.0
        self.playing, self.rate, self._corr = False, 1.0, 0.0
        self.snapped = False

    def reset(self):
        self.anchor_pos = self.anchor_time = 0.0
        self.playing, self.rate, self._corr = False, 1.0, 0.0
        self.snapped = False

    def update(self, position, is_playing, t_before, t_after, rate=1.0):
        t_s = (t_before + t_after) / 2.0
        rate = rate if (rate and rate > 0) else 1.0
        self.snapped = False
        if not self.playing and not is_playing:
            self.anchor_pos, self.anchor_time, self._corr, self.rate = position, t_s, 0.0, rate
            return
        predicted = self.position_at(t_s)
        err = position - predicted
        if (is_playing != self.playing) or abs(err) > self.seek_tol or rate != self.rate:
            self.anchor_pos, self.anchor_time, self._corr = position, t_s, 0.0
            self.snapped = True
        else:
            self.anchor_pos, self.anchor_time, self._corr = predicted, t_s, err
        self.playing, self.rate = is_playing, rate

    def position_at(self, t):
        if not self.playing:
            return self.anchor_pos
        base = self.anchor_pos + (t - self.anchor_time) * self.rate
        if self._corr:
            base += self._corr * min(1.0, max(0.0, t - self.anchor_time) * self.slew * 4.0)
        return base


class FrameFeat:
    """One 20 ms stereo-isolated audio feature frame, stamped in song time."""
    __slots__ = ('timestamp', 'song_position', 'mid_rms', 'side_rms', 'consonant_rms',
                 'vocal_energy', 'spectral_flux', 'onset_strength', 'vad', 'frame_duration')

    def __init__(self, timestamp, song_position, mid_rms, side_rms, consonant_rms,
                 vocal_energy, spectral_flux, onset_strength, vad, frame_duration):
        self.timestamp = timestamp
        self.song_position = song_position
        self.mid_rms = mid_rms
        self.side_rms = side_rms
        self.consonant_rms = consonant_rms
        self.vocal_energy = vocal_energy
        self.spectral_flux = spectral_flux
        self.onset_strength = onset_strength
        self.vad = bool(vad)
        self.frame_duration = frame_duration

    @property
    def onset(self):
        return self.onset_strength

    def __repr__(self):
        return ('FrameFeat(pos={:.3f}, vocal={:.4f}, side={:.4f}, onset={:.2f}, vad={})'
                .format(self.song_position, self.vocal_energy, self.side_rms,
                        self.onset_strength, self.vad))


class _Biquad:
    """Small RBJ high/low-pass filter; deliberately implemented without DSP packages."""
    def __init__(self, sample_rate, cutoff, kind):
        cutoff = min(max(10.0, float(cutoff)), sample_rate * 0.45)
        omega = 2.0 * math.pi * cutoff / sample_rate
        cosine, sine = math.cos(omega), math.sin(omega)
        alpha = sine / (2.0 * math.sqrt(0.5))
        if kind == 'highpass':
            b0, b1, b2 = (1.0 + cosine) / 2.0, -(1.0 + cosine), (1.0 + cosine) / 2.0
        else:
            b0, b1, b2 = (1.0 - cosine) / 2.0, 1.0 - cosine, (1.0 - cosine) / 2.0
        a0, a1, a2 = 1.0 + alpha, -2.0 * cosine, 1.0 - alpha
        self.b0, self.b1, self.b2 = b0 / a0, b1 / a0, b2 / a0
        self.a1, self.a2 = a1 / a0, a2 / a0
        self.x1 = self.x2 = self.y1 = self.y2 = 0.0

    def process(self, sample):
        value = (self.b0 * sample + self.b1 * self.x1 + self.b2 * self.x2 -
                 self.a1 * self.y1 - self.a2 * self.y2)
        self.x2, self.x1 = self.x1, sample
        self.y2, self.y1 = self.y1, value
        return value


class AudioFeatureExtractor:
    """Streaming, stdlib-only stereo mid/side formant and consonant-band VAD."""
    def __init__(self, sample_rate=16000, channels=2, frame_ms=20, side_cancel_gain=0.55):
        self.sample_rate = int(sample_rate)
        self.channels = int(channels)
        self.frame_samples = max(1, int(self.sample_rate * frame_ms / 1000.0))
        self.frame_duration = self.frame_samples / float(self.sample_rate)
        self.frame_bytes = self.frame_samples * self.channels * 2
        self.side_cancel_gain = float(side_cancel_gain)
        self._pending = bytearray()
        self._noise_floor = 0.002
        self._recent_vocal = deque(maxlen=2)
        self._previous_consonant = 0.0
        self._new_filters()

    def _new_filters(self):
        sr = self.sample_rate
        self._mid_hp, self._mid_lp = _Biquad(sr, 300.0, 'highpass'), _Biquad(sr, 3400.0, 'lowpass')
        self._side_hp, self._side_lp = _Biquad(sr, 300.0, 'highpass'), _Biquad(sr, 3400.0, 'lowpass')
        self._cons_hp, self._cons_lp = _Biquad(sr, 2500.0, 'highpass'), _Biquad(sr, 5500.0, 'lowpass')

    def reset(self):
        self._pending.clear()
        self._noise_floor = 0.002
        self._recent_vocal.clear()
        self._previous_consonant = 0.0
        self._new_filters()

    def process_pcm(self, pcm, start_position=0.0):
        """Convert interleaved signed-16 PCM into FrameFeat objects.

        ``start_position`` is the song position of the first complete sample in this chunk.
        Partial bytes are retained between calls, as subprocess pipes may split PCM frames.
        """
        if not pcm:
            return []
        self._pending.extend(pcm)
        frames = []
        frame_index = 0
        fmt = '<' + ('h' * (self.frame_samples * self.channels))
        while len(self._pending) >= self.frame_bytes:
            raw = bytes(self._pending[:self.frame_bytes])
            del self._pending[:self.frame_bytes]
            samples = struct.unpack(fmt, raw)
            mid_sum = side_sum = consonant_sum = 0.0
            for i in range(self.frame_samples):
                if self.channels >= 2:
                    left = samples[i * self.channels] / 32768.0
                    right = samples[i * self.channels + 1] / 32768.0
                else:
                    left = right = samples[i] / 32768.0
                mid = 0.5 * (left + right)
                side = 0.5 * (left - right)
                mid_formant = self._mid_lp.process(self._mid_hp.process(mid))
                side_formant = self._side_lp.process(self._side_hp.process(side))
                consonant = self._cons_lp.process(self._cons_hp.process(mid))
                mid_sum += mid_formant * mid_formant
                side_sum += side_formant * side_formant
                consonant_sum += consonant * consonant
            denom = float(self.frame_samples)
            mid_rms = math.sqrt(mid_sum / denom)
            side_rms = math.sqrt(side_sum / denom)
            consonant_rms = math.sqrt(consonant_sum / denom)
            vocal_energy = max(0.0, mid_rms - self.side_cancel_gain * side_rms)

            floor = self._noise_floor
            threshold = max(0.006, min(0.025, floor * 2.8))
            vad = vocal_energy > threshold and mid_rms > threshold
            if not vad:
                self._noise_floor = min(0.08, 0.995 * floor + 0.005 * min(vocal_energy, 0.08))
            else:
                self._noise_floor = max(0.0015, min(floor, vocal_energy * 0.45))

            previous_floor = min(self._recent_vocal) if self._recent_vocal else 0.0
            rise = max(0.0, vocal_energy - previous_floor)
            rise_rate = rise / max(0.012, previous_floor)
            flux = max(0.0, consonant_rms - self._previous_consonant)
            onset_strength = min(1.0, 0.55 * min(1.0, rise_rate / 2.5) +
                                 0.45 * min(1.0, flux / 0.035))
            self._recent_vocal.append(vocal_energy)
            self._previous_consonant = consonant_rms
            position = float(start_position or 0.0) + frame_index * self.frame_duration
            frames.append(FrameFeat(time.monotonic(), position, mid_rms, side_rms,
                                    consonant_rms, vocal_energy, flux, onset_strength,
                                    vad, self.frame_duration))
            frame_index += 1
        return frames


def extract_features(audio, sample_rate=16000, channels=2, frame_ms=20,
                     start_position=0.0, side_cancel_gain=0.55):
    """Offline feature extraction for raw interleaved s16le PCM (no NumPy/SciPy/librosa)."""
    extractor = AudioFeatureExtractor(sample_rate, channels, frame_ms, side_cancel_gain)
    return extractor.process_pcm(audio, start_position=start_position)


def _feature_onset_candidates(features):
    return [f for f in features if f.vad and f.onset_strength >= 0.14]


def align_tokens(words, features, line_start, line_end, pace=DEFAULT_PACE):
    """Acoustically refine heuristic word onsets from center-channel vocal activity.

    The feature envelope gates the phrase entry, then the prosodic schedule is fitted inside
    the observed vocal interval. Strong 50 ms rise/flux peaks are preferred; continuous vowels
    still constrain estimates to the real vocal region.
    """
    base = estimate_line(words, line_start, line_end, pace)
    features = sorted((f for f in (features or ())
                       if line_start - 0.12 <= f.song_position <= line_end),
                      key=lambda f: f.song_position)
    active = [f for f in features if f.vad]
    if not active:
        return base
    first_voice = active[0].song_position
    last_voice = active[-1].song_position + active[-1].frame_duration
    word_events = [(i, t, word) for i, (t, word) in enumerate(base) if word]
    if not word_events:
        return base
    seed_span = max(0.0, word_events[-1][1] - word_events[0][1])
    active_span = max(0.0, last_voice - first_voice)
    scale = min(1.25, active_span / seed_span) if seed_span > 0.02 else 1.0
    peaks = _feature_onset_candidates(active)
    out = list(base)
    assigned = []
    for order, (base_index, predicted, word) in enumerate(word_events):
        target = first_voice + (predicted - word_events[0][1]) * scale
        remaining = len(word_events) - order - 1
        upper = max(first_voice, last_voice - remaining * 0.035)
        target = min(upper, max(first_voice, target))
        usable_peaks = [f for f in peaks if abs(f.song_position - target) <= 0.16 and
                        all(abs(f.song_position - used) > 0.055 for used in assigned)]
        if usable_peaks:
            chosen = min(usable_peaks, key=lambda f: abs(f.song_position - target))
            target = chosen.song_position
        else:
            usable_active = [f for f in active if abs(f.song_position - target) <= 0.06 and
                             all(abs(f.song_position - used) > 0.03 for used in assigned)]
            if usable_active:
                target = min(usable_active, key=lambda f: abs(f.song_position - target)).song_position
        if assigned:
            target = max(target, assigned[-1] + 0.035)
        target = min(last_voice, max(first_voice, target))
        out[base_index] = (target, word)
        assigned.append(target)

    # If there is an existing rest marker, anchor it to the observed end of center vocal plus
    # a short release. The stereo instrumental tail is not allowed to hold the lyric onscreen.
    rest_indices = [i for i, (_, word) in enumerate(out) if not word]
    if rest_indices:
        last_word_time = max(t for t, word in out if word)
        clear_at = min(line_end - 0.001, max(last_word_time + 0.12, last_voice + 0.38))
        out[rest_indices[-1]] = (clear_at, '')
    return out


def refine_word_events(events, features, line_start=None, line_end=None, now=None,
                       entry_wait=0.35, pace=DEFAULT_PACE):
    """Causally refine one estimated line; safe to call every 150 ms during playback.

    Non-boundary transitions snap to a nearby vocal attack (±160 ms). Phrase-entry and
    post-caesura transitions wait for vocal activity up to ``entry_wait``; an observed attack
    is permitted one PCM-frame of capture tolerance. A 380 ms center-vocal freeze may advance
    a pending rest marker while stereo instruments continue.
    """
    refined = list(events or ())
    if not refined:
        return refined
    if line_start is None:
        line_start = next((t for t, w in refined if w), refined[0][0])
    if line_end is None:
        line_end = refined[-1][0] + 1.0
    features = sorted((f for f in (features or ())
                       if line_start - 0.12 <= f.song_position <= line_end and
                       (now is None or f.song_position <= now + 0.025)),
                      key=lambda f: f.song_position)
    if now is None:
        # Full-window/offline alignment: reuse the non-causal vocal-envelope fit.
        words = [w for _, w in refined if w]
        if words:
            aligned = align_tokens(words, features, line_start, line_end, pace)
            aligned_words = iter(t for t, w in aligned if w)
            aligned_rests = iter(t for t, w in aligned if not w)
            rest_fallback = next((t for t, w in refined if not w), None)
            out = []
            for t, word in refined:
                if word:
                    out.append((next(aligned_words), word))
                else:
                    clear_at = next(aligned_rests, rest_fallback if rest_fallback is not None else t)
                    out.append((clear_at, ''))
            return out
        return refined

    word_indices = [i for i, (_, word) in enumerate(refined) if word]
    if not word_indices:
        return refined
    active = [f for f in features if f.vad]
    peaks = _feature_onset_candidates(features)
    assigned_peaks = []
    previous_time = line_start - 0.05
    previous_word = ''
    for order, event_index in enumerate(word_indices):
        predicted, word = refined[event_index]
        boundary = (order == 0 or _is_clause_boundary(previous_word) or
                    (order > 0 and _parenthetical_starts(word)))
        target = predicted
        if boundary:
            low, high = predicted - 0.05, predicted + entry_wait + 0.05
        else:
            low, high = predicted - 0.16, predicted + 0.16
        candidates = [f for f in peaks if low <= f.song_position <= high and
                      f.song_position > previous_time + 0.025 and
                      all(abs(f.song_position - used) > 0.055 for used in assigned_peaks)]
        if candidates:
            chosen = min(candidates, key=lambda f: abs(f.song_position - predicted))
            target = chosen.song_position
            assigned_peaks.append(target)
        elif boundary and predicted <= now <= predicted + entry_wait:
            # Keep a scheduled entry just ahead of the clock while waiting; at the deadline
            # it releases even on silence, so missing/blocked audio cannot stall lyrics.
            target = min(predicted + entry_wait, max(predicted, now + 0.025))
        elif boundary and now > predicted + entry_wait:
            target = predicted + entry_wait

        if order and _repeat_transition([previous_word, word], 0, 1):
            # Chant/stutter timing remains isochronous; do not bend it toward incidental peaks.
            target = predicted
        min_step = min(0.10, max(0.035, (line_end - line_start) / max(40, len(word_indices) * 4)))
        target = max(target, previous_time + min_step)
        target = min(line_end - 0.001, max(line_start, target))
        refined[event_index] = (target, word)
        previous_time, previous_word = target, word

    rest_indices = [i for i, (_, word) in enumerate(refined) if not word]
    if rest_indices and active:
        last_voice = active[-1]
        freeze_at = last_voice.song_position + last_voice.frame_duration + 0.38
        instrumental = any(f.side_rms > 0.012 for f in features
                           if f.song_position > last_voice.song_position + last_voice.frame_duration)
        final_word_time = refined[word_indices[-1]][0]
        if instrumental and now >= final_word_time:
            # Keep the marker beyond a still-active phrase, then release at the first
            # 380 ms center-vocal freeze (never at the earlier heuristic guess).
            clear_at = min(line_end - 0.001, max(final_word_time + 0.12, freeze_at))
            rest_index = rest_indices[-1]
            refined[rest_index] = (clear_at, '')
    return refined


class LiveAudioTracker:
    """Fail-soft PipeWire/PulseAudio monitor reader with a 12-second feature ring buffer."""
    def __init__(self, position_provider=None, enabled=True, window_seconds=12.0,
                 sample_rate=16000, frame_ms=20, side_cancel_gain=0.55):
        self.position_provider = position_provider
        self.enabled = bool(enabled)
        self.window_seconds = float(window_seconds)
        self.extractor = AudioFeatureExtractor(sample_rate, 2, frame_ms, side_cancel_gain)
        self._frames = deque()
        self._lock = threading.RLock()
        self._extract_lock = threading.Lock()
        self._stop_event = threading.Event()
        self._thread = None
        self._process = None
        self.available = False
        self.error = None

    @staticmethod
    def _capture_commands():
        commands = []
        monitor_names = ['@DEFAULT_MONITOR@']
        pactl = shutil.which('pactl')
        if pactl:
            try:
                result = subprocess.run([pactl, 'get-default-sink'],
                                        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                        timeout=0.4, universal_newlines=True)
                sink = result.stdout.strip().splitlines()[0] if result.returncode == 0 and result.stdout.strip() else ''
                if sink and sink + '.monitor' not in monitor_names:
                    monitor_names.append(sink + '.monitor')
            except Exception:
                pass

        pw_cat = shutil.which('pw-cat')
        if pw_cat:
            for target in monitor_names:
                commands.append([pw_cat, '--record', '--raw', '--rate', '16000', '--channels', '2',
                                 '--format', 's16', '--target', target, '-'])
        pw_record = shutil.which('pw-record')
        if pw_record:
            for target in monitor_names:
                commands.append([pw_record, '--raw', '--rate', '16000', '--channels', '2',
                                 '--format', 's16', '--target', target, '-'])
        parec = shutil.which('parec')
        if parec:
            for target in monitor_names:
                commands.append([parec, '--device=' + target, '--format=s16le',
                                 '--rate=16000', '--channels=2', '--raw'])
        return commands

    def start(self):
        if not self.enabled:
            self.error = 'disabled'
            return False
        if self._thread and self._thread.is_alive():
            return True
        if not any(shutil.which(tool) for tool in ('pw-cat', 'pw-record', 'parec')):
            self.error = 'no PipeWire/PulseAudio capture tool found'
            return False
        self._stop_event.clear()
        self._thread = threading.Thread(target=self._reader, name='word-sync-audio', daemon=True)
        self._thread.start()
        return True

    def _append(self, frames):
        with self._lock:
            for frame in frames:
                if self._frames and frame.song_position < self._frames[-1].song_position - 0.5:
                    # A seek/backward jump invalidates the old playback-time ring.
                    self._frames.clear()
                self._frames.append(frame)
                cutoff = frame.song_position - self.window_seconds
                while self._frames and self._frames[0].song_position < cutoff:
                    self._frames.popleft()
            if frames:
                self.available = True

    def feed_pcm(self, pcm, song_position=0.0):
        """Feed PCM directly (also useful for offline tests and custom audio backends)."""
        with self._extract_lock:
            frames = self.extractor.process_pcm(pcm, start_position=song_position)
        self._append(frames)
        return frames

    def snapshot(self, start=None, end=None):
        with self._lock:
            frames = [f for f in self._frames
                      if (start is None or f.song_position >= start) and
                         (end is None or f.song_position <= end)]
        return sorted(frames, key=lambda f: f.song_position)

    def reset(self):
        with self._extract_lock:
            self.extractor.reset()
        with self._lock:
            self._frames.clear()
            self.available = False

    def _reader(self):
        commands = self._capture_commands()
        errors = []
        frame_bytes = self.extractor.frame_bytes
        for command in commands:
            if self._stop_event.is_set():
                break
            proc = None
            try:
                proc = subprocess.Popen(command, stdin=subprocess.DEVNULL,
                                       stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                       bufsize=0)
                with self._lock:
                    self._process = proc
                pending = bytearray()
                while not self._stop_event.is_set():
                    chunk = proc.stdout.read(frame_bytes - len(pending))
                    if not chunk:
                        break
                    pending.extend(chunk)
                    if len(pending) < frame_bytes:
                        continue
                    pcm = bytes(pending[:frame_bytes])
                    del pending[:frame_bytes]
                    position = self.position_provider() if self.position_provider else None
                    if position is None:
                        continue
                    frame_start = max(0.0, float(position) - self.extractor.frame_duration)
                    with self._extract_lock:
                        features = self.extractor.process_pcm(pcm, start_position=frame_start)
                    # The capture read is isolated from the UI/main playback loop.
                    self._append(features)
                if self._stop_event.is_set():
                    break
                errors.append('{} exited'.format(os.path.basename(command[0])))
            except Exception as exc:
                errors.append('{}: {}'.format(os.path.basename(command[0]), exc))
            finally:
                if proc is not None:
                    try:
                        if proc.poll() is None:
                            proc.terminate()
                            try:
                                proc.wait(timeout=0.25)
                            except Exception:
                                proc.kill()
                    except Exception:
                        pass
                    try:
                        if proc.stdout:
                            proc.stdout.close()
                    except Exception:
                        pass
                with self._lock:
                    if self._process is proc:
                        self._process = None
            if self.available or self._stop_event.is_set():
                break
        if errors and not self.available:
            self.error = errors[-1]

    def stop(self):
        self._stop_event.set()
        with self._lock:
            proc = self._process
        if proc is not None:
            try:
                if proc.poll() is None:
                    proc.terminate()
                    try:
                        proc.wait(timeout=0.25)
                    except Exception:
                        proc.kill()
            except Exception:
                pass
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=0.5)
        with self._lock:
            self._process = None


def get_player_state(player=None):
    """One playerctl round trip. Returns a dict (with 't_before'/'t_after' monotonic stamps
    around the call, for unbiased clock sampling) or None."""
    cmd = ['playerctl']
    if player:
        cmd += ['--player', player]
    cmd += ['metadata', '--format',
            'STATUS={{status}}||ARTIST={{artist}}||TITLE={{title}}||POS={{position}}'
            '||LEN={{mpris:length}}||RATE={{playerctl:rate}}||TID={{mpris:trackid}}']
    t_before = time.monotonic()
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=1.5)
    except Exception:
        return None
    t_after = time.monotonic()
    if p.returncode != 0:
        return None
    line = p.stdout.strip()
    if not line:
        return None
    fields = {}
    for part in line.split('||'):
        if '=' in part:
            k, v = part.split('=', 1)
            fields[k] = v

    def _f(key, scale=1.0, default=0.0):
        try:
            return float(fields.get(key, default)) / scale
        except (TypeError, ValueError):
            return default

    artist = fields.get('ARTIST', '').strip()
    title = fields.get('TITLE', '').strip()
    return {
        'status': fields.get('STATUS', 'Stopped'),
        'artist': artist,
        'title': title,
        'position': _f('POS', 1_000_000.0),
        'duration': _f('LEN', 1_000_000.0),
        'rate': _f('RATE', 1.0, 1.0) or 1.0,
        'track_id': fields.get('TID', ''),
        'song_key': f'{artist}---{title}',
        't_before': t_before,
        't_after': t_after,
    }


