def load_config(path):
    cfg = {}
    if not os.path.exists(path):
        return cfg
    try:
        with open(path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                if '=' not in line:
                    continue
                k, v = line.split('=', 1)
                k = k.strip().replace('-', '_')
                v = v.strip().strip('"').strip("'")
                cfg[k] = v
    except Exception:
        pass
    return cfg


def _as_bool(v, default):
    if v is None:
        return default
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() in ('1', 'true', 'yes', 'on')


def _as_float(v, default):
    if v is None:
        return default
    try:
        return float(v)
    except ValueError:
        return default


